
    create table admin_audit_logs (
        admin_user_id bigint not null,
        created_at timestamp(6) not null,
        id bigint generated by default as identity,
        target_id bigint not null,
        target_type varchar(30) not null check (target_type in ('USER','ORGANIZATION','CLUB','EVENT','PLACEMENT')),
        action varchar(40) not null check (action in ('USER_ACTIVATED','USER_DEACTIVATED','USER_ROLE_CHANGED','ORGANIZATION_ACTIVATED','ORGANIZATION_DEACTIVATED','CLUB_ACTIVATED','CLUB_DEACTIVATED','EVENT_CANCELLED','PLACEMENT_CREATED','PLACEMENT_UPDATED','PLACEMENT_PUBLISHED','PLACEMENT_CLOSED')),
        details TEXT not null,
        primary key (id)
    );

    create table club_members (
        active boolean not null,
        club_id bigint not null,
        id bigint generated by default as identity,
        joined_at timestamp(6) not null,
        user_id bigint not null,
        primary key (id),
        constraint uk_club_member unique (club_id, user_id)
    );

    create table clubs (
        active boolean not null,
        created_at timestamp(6) not null,
        id bigint generated by default as identity,
        leader_id bigint not null,
        organization_id bigint not null,
        updated_at timestamp(6) not null,
        name varchar(100) not null unique,
        description TEXT,
        email varchar(255),
        logo varchar(255),
        phone_number varchar(255),
        primary key (id)
    );

    create table event_feedback (
        rating integer not null check ((rating<=5) and (rating>=1)),
        created_at timestamp(6) not null,
        event_id bigint not null,
        id bigint generated by default as identity,
        updated_at timestamp(6) not null,
        user_id bigint not null,
        comment TEXT,
        primary key (id),
        constraint uk_event_feedback_user unique (event_id, user_id)
    );

    create table event_target_branches (
        event_id bigint not null,
        branch varchar(255) not null,
        constraint uk_event_target_branch primary key (event_id, branch)
    );

    create table event_target_sections (
        event_id bigint not null,
        section varchar(255) not null,
        constraint uk_event_target_section primary key (event_id, section)
    );

    create table event_target_years (
        academic_year integer not null,
        event_id bigint not null,
        constraint uk_event_target_year primary key (event_id, academic_year)
    );

    create table events (
        capacity integer not null,
        end_time time(6) not null,
        event_date date not null,
        start_time time(6) not null,
        created_at timestamp(6) not null,
        id bigint generated by default as identity,
        organization_id bigint not null,
        registration_deadline timestamp(6) not null,
        updated_at timestamp(6) not null,
        title varchar(150) not null,
        description TEXT,
        status varchar(255) not null check (status in ('UPCOMING','ONGOING','COMPLETED','CANCELLED','DELETED')),
        type varchar(255) not null check (type in ('ONLINE','OFFLINE','HYBRID')),
        venue varchar(255) not null,
        primary key (id)
    );

    create table learning_resource_tags (
        resource_id bigint not null,
        tag varchar(50) not null,
        constraint uk_learning_resource_tag primary key (resource_id, tag)
    );

    create table learning_resources (
        active boolean not null,
        created_at timestamp(6) not null,
        id bigint generated by default as identity,
        organization_id bigint not null,
        updated_at timestamp(6) not null,
        category varchar(80) not null,
        title varchar(150) not null,
        url varchar(2048) not null,
        description TEXT not null,
        primary key (id)
    );

    create table notification_preferences (
        event_cancelled boolean not null,
        event_reminder boolean not null,
        event_updated boolean not null,
        registration_successful boolean not null,
        id bigint generated by default as identity,
        user_id bigint not null,
        primary key (id),
        constraint uk_notification_preferences_user unique (user_id)
    );

    create table notifications (
        read boolean not null,
        created_at timestamp(6) not null,
        event_id bigint,
        id bigint generated by default as identity,
        user_id bigint not null,
        message TEXT not null,
        title varchar(255) not null,
        type varchar(255) not null check (type in ('REGISTRATION_SUCCESSFUL','EVENT_UPDATED','EVENT_CANCELLED','EVENT_REMINDER')),
        primary key (id)
    );

    create table organizations (
        active boolean not null,
        created_at timestamp(6) not null,
        id bigint generated by default as identity,
        leader_id bigint not null,
        updated_at timestamp(6) not null,
        name varchar(100) not null unique,
        description TEXT,
        email varchar(255),
        logo varchar(255),
        phone_number varchar(255),
        website varchar(255),
        primary key (id)
    );

    create table placement_applications (
        applied_at timestamp(6) not null,
        id bigint generated by default as identity,
        placement_id bigint not null,
        user_id bigint not null,
        status varchar(20) not null check (status in ('SUBMITTED')),
        primary key (id),
        constraint uk_placement_application_user unique (placement_id, user_id)
    );

    create table placements (
        application_deadline timestamp(6) not null,
        created_at timestamp(6) not null,
        created_by_user_id bigint not null,
        id bigint generated by default as identity,
        updated_at timestamp(6) not null,
        status varchar(20) not null check (status in ('DRAFT','PUBLISHED','CLOSED')),
        type varchar(30) not null check (type in ('FULL_TIME','INTERNSHIP','PART_TIME','CO_OP','OTHER')),
        compensation varchar(100),
        company_name varchar(150) not null,
        location varchar(150) not null,
        title varchar(150) not null,
        description TEXT not null,
        eligibility_criteria TEXT,
        primary key (id)
    );

    create table registrations (
        cancelled_at timestamp(6),
        event_id bigint not null,
        id bigint generated by default as identity,
        registered_at timestamp(6) not null,
        user_id bigint not null,
        status varchar(255) not null check (status in ('REGISTERED','CANCELLED')),
        primary key (id),
        constraint uk_user_event unique (user_id, event_id)
    );

    create table users (
        academic_year integer,
        active boolean not null,
        profile_verified boolean default false not null,
        section varchar(5),
        created_at timestamp(6),
        id bigint generated by default as identity,
        updated_at timestamp(6),
        roll_number varchar(30) unique,
        branch varchar(50),
        username varchar(50) not null unique,
        college_email varchar(150),
        email varchar(255) not null unique,
        first_name varchar(255) not null,
        last_name varchar(255) not null,
        password varchar(255) not null,
        phone_number varchar(255),
        profile_image varchar(255),
        role varchar(255) not null check (role in ('STUDENT','CLUB_ADMIN','FACULTY','ADMIN')),
        primary key (id)
    );

